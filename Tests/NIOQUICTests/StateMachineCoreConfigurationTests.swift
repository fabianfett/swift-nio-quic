import NIOCore
@_spi(Essentials) @_spi(ProtocolProvider) import QUICStateMachine
import Testing

@testable import NIOQUIC

/// The state machine connections in these tests are never created.
@available(anyAppleOS 26, *)
private struct NoConsumer: QUICStreamConsumer {
    typealias StreamState = Void

    func makeStreamState(_ stream: inout QUICStream<Self>) {}

    mutating func processStreams(_ streams: inout QUICStreamIterator<Self>) {
        while streams.next() != nil {}
    }
}

@Suite(.timeLimit(.minutes(1)))
struct StateMachineCoreConfigurationTests {
    /// PMTUD searches up to the maximum payload plus the IP and UDP headers to the peer: 28 bytes
    /// over IPv4, also to an IPv4-mapped IPv6 address, and 48 over IPv6.
    @available(anyAppleOS 26, *)
    @Test(arguments: [
        ("127.0.0.1", 28), ("192.0.2.17", 28), ("::ffff:192.0.2.17", 28), ("::1", 48), ("2001:db8::1:2", 48),
        ("::192.0.2.1", 48), ("64:ff9b::192.0.2.1", 48),
    ])
    func probingCapsTheMTUAtTheMaximumPlusTheHeaders(ipAddress: String, headerSize: Int) throws {
        var configuration = QUICConfiguration.forClient(
            verificationConfiguration: .rawPublicKeys(publicKeyFilePath: p256PublicKeyPath),
            applicationProtocols: ["h3"]
        )
        configuration.initialPacketSize = .matchingClientInitial(upTo: 1400)
        let coreConfiguration = try StateMachineQUICConnection<NoConsumer>.clientCoreConfiguration(
            configuration,
            sourceConnectionID: Self.connectionID(length: 8),
            serverName: "example.com",
            asyncVerifier: nil,
            remoteAddress: try SocketAddress(ipAddress: ipAddress, port: 4433)
        )

        #expect(coreConfiguration.maxDatagramSize == 1200)
        #expect(coreConfiguration.pmtudEnabled)
        #expect(coreConfiguration.ipUDPHeaderSize == headerSize)
        #expect(coreConfiguration.interfaceMTU == 1400 + headerSize)
    }

    @available(anyAppleOS 26, *)
    private static func connectionID(length: Int) -> NIOQUIC.QUICConnectionID {
        NIOQUIC.QUICConnectionID(bytes: [UInt8](repeating: 0x2A, count: length).span)
    }

    /// A connection tells its peer not to migrate only if it has no spare connection IDs, which
    /// zero-length ones don't (RFC 9000 Sections 9.5 and 18.2). It takes as many connection IDs
    /// as the SwiftNetwork driver does, and issues its own.
    @available(anyAppleOS 26, *)
    @Test(arguments: [0, 8])
    func onlyConnectionsWithoutConnectionIDsDisableActiveMigration(connectionIDLength: Int) throws {
        let remoteAddress = try SocketAddress(ipAddress: "127.0.0.1", port: 4433)
        let client = try StateMachineQUICConnection<NoConsumer>.clientCoreConfiguration(
            QUICConfiguration.forClient(
                verificationConfiguration: .rawPublicKeys(publicKeyFilePath: p256PublicKeyPath),
                applicationProtocols: ["h3"]
            ),
            sourceConnectionID: Self.connectionID(length: connectionIDLength),
            serverName: "example.com",
            asyncVerifier: nil,
            remoteAddress: remoteAddress
        )
        let server = try StateMachineQUICConnection<NoConsumer>.serverCoreConfiguration(
            QUICConfiguration.forServer(
                serverName: "example.com",
                authenticationConfiguration: .rawPublicKeys(
                    publicKeyFilePath: p256PublicKeyPath,
                    privateKeyFilePath: p256PrivateKeyPath
                ),
                applicationProtocols: ["h3"]
            ),
            sourceConnectionID: Self.connectionID(length: connectionIDLength),
            statelessResetTokenGenerator: .defaultWithAutoGeneratedKey,
            authenticator: nil,
            remoteAddress: remoteAddress
        )

        for coreConfiguration in [client, server] {
            #expect(coreConfiguration.disableActiveMigration == (connectionIDLength == 0))
            #expect(coreConfiguration.activeConnectionIDLimit == 64)
            #expect(!coreConfiguration.automaticallyIssueConnectionIDs)
        }
    }
}
